export const DEFAULT_PALETTE = "terre";
export const PALETTE_IDS = ["terre", "plantain", "ndole", "piment"] as const;
export type PaletteId = typeof PALETTE_IDS[number];
export function isPaletteId(value: unknown): value is PaletteId { return typeof value === "string" && (PALETTE_IDS as readonly string[]).includes(value); }
export function resolveColors(palette: unknown, dark: boolean): ThemeColors {
 return themes[isPaletteId(palette) ? palette : DEFAULT_PALETTE][dark ? "dark" : "light"];
}

